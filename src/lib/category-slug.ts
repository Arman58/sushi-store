/**
 * Латинский slug из названия категории. Не-латиница отбрасывается; пустой результат
 * (название целиком на армянском/русском) означает "slug нужно сгенерировать иначе".
 */
export function slugifyCategoryName(name: string): string {
    return (
        name
            .toLowerCase()
            .trim()
            .replace(/\s+/g, "-")
            .replace(/[^a-z0-9-]/g, "")
            // "Десерты UI-тест" давало "-ui-": схлопываем повторы и убираем дефисы по краям
            .replace(/-{2,}/g, "-")
            .replace(/^-+|-+$/g, "")
    );
}
